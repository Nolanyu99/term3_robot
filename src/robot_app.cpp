void robot_app_setup()
{
  programming_viva_setup();
  Serial.println("=== Easy difficulty autonomous app ===");
  Serial.println("Flow: calibrate -> line to B tag -> tunnel -> arena fertile planting.");
  Serial.println("Serial: 0/x stop-toggle, r restart Easy flow, d manual dispense.");
}

void robot_app_loop()
{
  serviceServoPulses();
  update_turn_angle();
  messagesLoop();
  printEasyStatus();

  if (startup_cal_state != StartupCalState::Ready) {
    easy_state = EasyState::Calibrating;
    programming_viva_loop();
    return;
  }

  runEasyReadyLoop();
}
