enum class EasyState {
  Calibrating,
  BaseLineToAirlockB,
  Tunnel,
  ArenaPlanting,
  Complete,
  Stopped,
};

constexpr unsigned long EASY_STATUS_INTERVAL_MS = 1000;
constexpr unsigned long EASY_FERTILITY_REPLY_TIMEOUT_MS = 1500;

EasyState easy_state = EasyState::Calibrating;
EasyState easy_resume_state = EasyState::BaseLineToAirlockB;
unsigned long easy_last_status_ms = 0;
unsigned long easy_line_status_ms = 0;
bool easy_started = false;
bool easy_airlock_requested = false;
bool easy_tunnel_started = false;
uint8_t easy_planted_count = 0;

const char* easyStateName(EasyState state)
{
  switch (state) {
    case EasyState::Calibrating: return "calibrating";
    case EasyState::BaseLineToAirlockB: return "base_line_to_airlock_b";
    case EasyState::Tunnel: return "tunnel";
    case EasyState::ArenaPlanting: return "arena_planting";
    case EasyState::Complete: return "complete";
    case EasyState::Stopped: return "stopped";
  }

  return "unknown";
}

void printEasyStatus()
{
  const unsigned long now_ms = millis();
  if (now_ms - easy_last_status_ms < EASY_STATUS_INTERVAL_MS) {
    return;
  }

  easy_last_status_ms = now_ms;
  Serial.print("easy_state=");
  Serial.print(easyStateName(easy_state));
  Serial.print(" mission_phase=");
  Serial.print(static_cast<int>(mission_phase));
  Serial.print(" seeds_left=");
  Serial.print(seeds);
  Serial.print(" planted=");
  Serial.print(easy_planted_count);
  Serial.print(" mqtt=");
  Serial.println(messagesConnected() ? 1 : 0);
}

void processEasySerial()
{
  while (Serial.available() > 0) {
    const char command = static_cast<char>(Serial.read());

    if (command == '0' || command == 'x' || command == 'X') {
      running = !running;
      if (!running) {
        if (easy_state != EasyState::Stopped) {
          easy_resume_state = easy_state;
        }
        stopMotors();
        easy_state = EasyState::Stopped;
        Serial.println("easy_stop=serial");
      } else {
        easy_state = easy_resume_state;
        Serial.println("easy_resume=serial");
      }
    } else if (command == 'r' || command == 'R') {
      easy_state = EasyState::BaseLineToAirlockB;
      easy_airlock_requested = false;
      easy_tunnel_started = false;
      mission_phase = MissionPhase::BaseToGate;
      running = true;
      run_enabled = true;
      Serial.println("easy_restart=serial");
    } else if (command == 'd' || command == 'D') {
      if (seeds > 0) {
        dispenseOne();
        --seeds;
        ++easy_planted_count;
        Serial.println("easy_manual_dispense=1");
      }
    }
  }
}

void updateEasyButtons()
{
  const int off_button_pressed = digitalRead(OffButtonPin);
  const int revive_button_pressed = digitalRead(RevButtonPin);

  Reviving = false;

  if (off_button_pressed == LOW && previousOffButtonPressed != LOW) {
    running = !running;
    delay(50);

    if (!running) {
      if (easy_state != EasyState::Stopped) {
        easy_resume_state = easy_state;
      }
      easy_state = EasyState::Stopped;
      stopMotors();
      Serial.println("easy_stop=button");
    } else {
      easy_state = easy_resume_state;
      Serial.println("easy_resume=button");
    }
  } else if (revive_button_pressed == LOW) {
    Reviving = true;
    delay(50);
  }

  previousOffButtonPressed = off_button_pressed;
}

bool readRFIDUid(char* uid, size_t uid_size)
{
  if (!(rfid.PICC_IsNewCardPresent() && rfid.PICC_ReadCardSerial())) {
    return false;
  }

  if (millis() - lastScanTime < RFID_SCAN_COOLDOWN_MS) {
    rfid.PICC_HaltA();
    return false;
  }

  uidToText(uid, uid_size);
  lastScanTime = millis();
  rfid.PICC_HaltA();
  return uid[0] != '\0';
}

bool easyRequestAirlockFromBaseLine()
{
  char uid[32];
  if (!readRFIDUid(uid, sizeof(uid))) {
    return false;
  }

  stopMotors();
  Serial.print("easy_base_airlock_tag=");
  Serial.println(uid);

  if (messagesConnected()) {
    const bool ok = messagesSendOpenAirlock('B', uid);
    Serial.print("easy_open_airlock_b_sent=");
    Serial.println(ok ? 1 : 0);
  } else {
    Serial.println("easy_warning=no_mqtt_for_airlock_b");
  }

  easy_airlock_requested = true;
  return true;
}

bool easyHandleArenaRFID()
{
  char uid[32];
  if (!readRFIDUid(uid, sizeof(uid))) {
    return false;
  }

  stopMotors();
  Serial.print("easy_arena_tag=");
  Serial.println(uid);

  bool fertile = false;
  int8_t tag_x = -1;
  int8_t tag_y = -1;
  uint8_t state = 0;

  if (messagesConnected() && messagesSendIsFertile(uid)) {
    if (messagesWaitForFertilityReply(
          uid,
          EASY_FERTILITY_REPLY_TIMEOUT_MS,
          &tag_x,
          &tag_y,
          &state)) {
      fertile = state == 2;
      Serial.print("easy_fertility_reply x=");
      Serial.print(tag_x);
      Serial.print(" y=");
      Serial.print(tag_y);
      Serial.print(" state=");
      Serial.println(state);
    } else {
      Serial.println("easy_warning=fertility_no_reply");
    }
  } else {
    Serial.println("easy_warning=fertility_request_not_sent");
  }

  if (fertile && seeds > 0) {
    centreAfterRFID();
    dispenseOne();
    --seeds;
    ++easy_planted_count;
    messagesSendSeedPlanted(uid);

    Serial.print("easy_seed_planted uid=");
    Serial.print(uid);
    Serial.print(" seeds_left=");
    Serial.println(seeds);

    if (seeds <= 0) {
      easy_state = EasyState::Complete;
      stopMotors();
      Green();
    }

    return true;
  }

  Serial.print("easy_no_plant fertile=");
  Serial.print(fertile ? 1 : 0);
  Serial.print(" seeds_left=");
  Serial.println(seeds);
  return false;
}

void runEasyLineFollowingStep()
{
  if (millis() - last_control_ms < CONTROL_INTERVAL_MS) {
    return;
  }

  last_control_ms = millis();
  read_rc_discharge_times();
  update_line_following();
}

void runEasyBaseLineStep()
{
  if (easyRequestAirlockFromBaseLine()) {
    easy_state = EasyState::Tunnel;
    return;
  }

  runEasyLineFollowingStep();
}

void runEasyTunnelStep()
{
  if (!easy_tunnel_started) {
    startTunnelEntry();
    easy_tunnel_started = true;
  }

  if (mission_phase == MissionPhase::Tunnel &&
      millis() - last_control_ms >= CONTROL_INTERVAL_MS) {
    last_control_ms = millis();
    run_tunnel_step();
  }

  if (mission_phase == MissionPhase::Arena) {
    easy_state = EasyState::ArenaPlanting;
    stopMotors();
    Serial.println("easy_phase=arena_planting");
  }
}

void runEasyArenaPlantingStep()
{
  if (seeds <= 0) {
    easy_state = EasyState::Complete;
    stopMotors();
    Green();
    return;
  }

  if (easyHandleArenaRFID()) {
    return;
  }

  runEasyLineFollowingStep();

  if (millis() - easy_line_status_ms >= LINE_STATUS_INTERVAL_MS) {
    easy_line_status_ms = millis();
    print_line_status();
  }
}

void runEasyReadyLoop()
{
  processEasySerial();
  updateEasyButtons();
  read_rc_discharge_times();

  if (!messagesRobotAllowedToMove()) {
    run_enabled = false;
    if (easy_state != EasyState::Stopped) {
      easy_resume_state = easy_state;
    }
    easy_state = EasyState::Stopped;
    stopMotors();
    Red();
    delay(25);
    return;
  }

  if (!running || easy_state == EasyState::Stopped) {
    run_enabled = false;
    Flash(previousStateRed);
    ++previousStateRed;
    stopMotors();
    delay(25);
    return;
  }

  run_enabled = true;

  if (Reviving) {
    Green();
    stopMotors();
    delay(500);
    setMotors(-BASE_SPEED, -BASE_SPEED);
    return;
  }

  if (!easy_started) {
    easy_started = true;
    easy_state = EasyState::BaseLineToAirlockB;
    last_control_ms = millis();
    Serial.println("easy_start=auto_base_line_to_airlock_b");
  }

  Red();

  switch (easy_state) {
    case EasyState::Calibrating:
      easy_state = EasyState::BaseLineToAirlockB;
      break;
    case EasyState::BaseLineToAirlockB:
      runEasyBaseLineStep();
      break;
    case EasyState::Tunnel:
      runEasyTunnelStep();
      break;
    case EasyState::ArenaPlanting:
      runEasyArenaPlantingStep();
      break;
    case EasyState::Complete:
      stopMotors();
      Green();
      break;
    case EasyState::Stopped:
      stopMotors();
      break;
  }
}

